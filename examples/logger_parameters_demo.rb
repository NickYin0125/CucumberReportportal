# frozen_string_literal: true

ENV["BUNDLE_GEMFILE"] ||= File.expand_path("../Gemfile", __dir__)
require "bundler/setup"
require "fileutils"
require "json"
require "optparse"
require "rbconfig"
require "securerandom"
require "time"
require "tmpdir"
require_relative "../lib/reportportal_cucumber"

# Runs the same parameter examples through a real Cucumber World, optionally to RP.
module LoggerParametersDemo
  extend ::Cucumber::Glue::Dsl

  ROOT = File.expand_path("..", __dir__)
  PAYLOAD = { order_id: "ORD-123", status: "accepted", amount: 125.50 }.freeze

  # @param file [String] Path to the example attachment.
  # @return [Array<Hash>]
  def self.cases(file:)
    [
      { message: "01 message only: terminal", options: {} },
      { message: "02 report:true: terminal and reports", options: { report: true } },
      { message: "03 attach:true: legacy reporting switch", options: { attach: true } },
      { message: "04 json Hash with report:true", options: { report: true, json: PAYLOAD } },
      { message: "05 json String with attach:true", options: { attach: true, json: JSON.generate(PAYLOAD) } },
      { message: "06 file with report:true", options: { report: true, file: file } },
      { message: "07 json without reporting: terminal summary", options: { json: PAYLOAD } },
      { message: "08 file without reporting: terminal summary", options: { file: file } },
      { message: "09 report:false overrides attach:true",
        options: { attach: true, report: false, file: file, json: PAYLOAD } }
    ]
  end

  # @return [void]
  def self.install_steps
    World(ReportportalCucumber::Cucumber::World)

    Around do |_scenario, run|
      AppLog.with_logger(Automation::CucumberLogger.new(world: self)) { run.call }
    end

    When("I demonstrate logger parameter example {int}") do |number|
      file = File.join(ENV.fetch("APPLOG_DEMO_DIR"), "evidence.txt")
      example = LoggerParametersDemo.cases(file: file).fetch(number - 1)
      AppLog.info(example.fetch(:message), **example.fetch(:options))
    end
  end

  # @param arguments [Array<String>] Optional --live flag.
  # @return [Integer] Cucumber exit status, including incomplete-reporting failures.
  def self.run(arguments)
    live = false
    parser = OptionParser.new do |options|
      options.banner = "Usage: bundle exec ruby examples/logger_parameters_demo.rb [--live]"
      options.on("--live", "Create a ReportPortal launch using RP_ENDPOINT, RP_PROJECT and RP_API_KEY") { live = true }
    end
    parser.parse!(arguments)
    raise ArgumentError, parser.banner unless arguments.empty?

    if live
      missing = %w[RP_ENDPOINT RP_PROJECT RP_API_KEY].select { |key| ENV[key].to_s.strip.empty? }
      raise ArgumentError, "Live mode requires: #{missing.join(', ')}" unless missing.empty?
    end

    base = File.join(ROOT, "tmp")
    FileUtils.mkdir_p(base)
    directory = Dir.mktmpdir("logger-parameters-", base)
    file = File.join(directory, "evidence.txt")
    File.write(file, "Order: ORD-123\nStatus: accepted\nEvidence generated by the AppLog parameter demo.\n")
    configuration = File.join(directory, "reportportal.yml")
    File.write(configuration, "{}\n")
    bootstrap = File.join(directory, "bootstrap.rb")
    File.write(bootstrap, "# frozen_string_literal: true\nrequire #{File.expand_path(__FILE__).dump}\nLoggerParametersDemo.install_steps\n")
    feature = File.join(directory, "logger_parameters.feature")
    steps = cases(file: file).each_index.map { |index| "    When I demonstrate logger parameter example #{index + 1}" }
    File.write(feature, "Feature: AppLog parameter showcase\n\n  Scenario: Compare terminal and report routing\n#{steps.join("\n")}\n")

    launch = "logger-parameters-#{Time.now.utc.strftime('%Y%m%dT%H%M%S')}-#{SecureRandom.hex(3)}"
    environment = ENV.keys.grep(/\A(?:RP_|CUCUMBER_)/).to_h { |key| [key, nil] }.merge(
      "RP_ENABLED" => live.to_s,
      "RP_CONFIG" => configuration,
      "RP_ENDPOINT" => live ? ENV.fetch("RP_ENDPOINT") : nil,
      "RP_PROJECT" => live ? ENV.fetch("RP_PROJECT") : nil,
      "RP_API_KEY" => live ? ENV.fetch("RP_API_KEY") : nil,
      "RP_LAUNCH" => launch,
      "RP_LAUNCH_DESCRIPTION" => "Nine AppLog.info parameter combinations; only cases 02-06 enter reports.",
      "RP_CLIENT_JOIN" => "false",
      "RP_REQUIRE_COMPLETE_REPORTING" => "true",
      "RP_BATCH_SIZE_LOGS" => "1",
      "RP_FLUSH_INTERVAL" => "0.1",
      "RP_CONSOLE_MIRROR" => "false",
      "RP_EXIT_FLUSH_TIMEOUT_MS" => "15000",
      "RP_SPOOL_DIR" => File.join(directory, "spool"),
      "CUCUMBER_PUBLISH_ENABLED" => "false",
      "CUCUMBER_PUBLISH_QUIET" => "true",
      "APPLOG_DEMO_DIR" => directory
    )
    metadata = { mode: live ? "live" : "offline", launch_name: live ? launch : nil,
                 report_cases: (2..6).to_a, output_directory: directory }
    File.write(File.join(directory, "run.json"), JSON.pretty_generate(metadata) + "\n")

    puts "Mode: #{metadata.fetch(:mode)}; only cases 02-06 enter reports."
    puts "RP launch: #{launch}" if live
    puts "Reports: #{directory}\n\n"
    command = [RbConfig.ruby, Gem.bin_path("cucumber", "cucumber"), "--no-profile", "--publish-quiet",
               "--require", bootstrap, feature,
               "--format", "progress", "--out", File.join(directory, "progress.txt"),
               "--format", "html", "--out", File.join(directory, "report.html"),
               "--format", "message", "--out", File.join(directory, "messages.ndjson"),
               "--format", "ReportPortal::Cucumber::Formatter", "--out", File.join(directory, "rp-formatter.log")]
    system(environment, *command, chdir: directory)
    status = $?.exitstatus || 1
    puts "\nCucumber exit: #{status}; native HTML: #{File.join(directory, 'report.html')}"
    if live
      endpoint = ENV.fetch("RP_ENDPOINT").sub(%r{/+\z}, "")
      puts "RP UI: #{endpoint}/ui/##{ENV.fetch('RP_PROJECT')}/launches/all"
      puts "Open launch: #{launch}; cases 01 and 07-09 should have no AppLog evidence."
    end
    status
  end
end

if $PROGRAM_NAME == __FILE__
  begin
    exit LoggerParametersDemo.run(ARGV)
  rescue ArgumentError, OptionParser::ParseError => error
    warn error.message
    exit 2
  end
end
